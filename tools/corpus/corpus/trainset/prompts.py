"""초안 모델에 주는 지시문(설계 §3·§5, ADR-0039·0040).

질문 지시문은 JSON(질문·답 근거·가능 여부)을, 목표 답 지시문은 학생 모델이 받을 운영 프롬프트를 그대로 보여 주고
모범 답 글만 받는다. 학교 이름·학과 같은 특정 값은 지시문에 넣지 않는다(문서에서 온 글만 쓴다).
"""

from __future__ import annotations

REFUSAL = "제공된 문서에서는 확인할 수 없습니다."

KIND_RULES = {
    "fact": "답이 글에 그대로 적힌 값 하나(날짜·기간·금액·인원·연락처·장소 등)인 질문을 만든다.",
    "procedure": "글에 적힌 신청·제출·처리 방법이나 절차를 묻는 질문을 만든다.",
    "table": "글의 표에서 한 행과 한 열을 함께 가리켜야 값이 하나로 정해지는 질문을 만든다. 질문에 행 이름과 열 이름을 담는다.",
    "multi": "두 글을 모두 읽어야 답할 수 있는 질문을 만든다. 한 글만 읽으면 답이 모자라야 한다.",
    "partial": "두 가지를 함께 묻는 질문을 만든다. 하나는 글에 답이 있고, 다른 하나는 글에 답이 없어야 한다.",
    "refuse_guide": "이 글과 같은 일을 다루지만 글에는 답이 없는 것을 묻는 질문을 만든다"
                    "(예: 글에 기간만 있으면 비용이나 대상을 묻는다). 학교에 물을 만한 것이어야 한다.",
    "refuse_offtopic": "대학 안내 챗봇에 물을 만하지만 학교 안내 문서에는 답이 없을 질문을 만든다"
                       "(다른 학교, 개인 사정에 대한 판단, 학교 밖 정보 등). 사람 이름·연락처는 쓰지 않는다.",
}
STYLE_RULES = {
    "짧은 구어체": "반말 섞인 짧은 구어체로, 한 문장으로 쓴다.",
    "정중체": "'~인가요?', '~하나요?' 같은 정중한 말투로 쓴다.",
    "상황 설명형": "자기 상황을 한 줄 설명한 뒤 묻는다.",
    "쉬운 한국어": "한국어가 서툰 사람이 쓰듯 쉬운 낱말로 짧게 쓴다.",
}


def question_prompt(item: dict) -> str:
    """질문 초안 지시문. 엉뚱한 근거 종류는 글 없이 만든다."""
    kind = item["kind"]
    # 상투문을 뺀 글(draft_text)을 준다 — 없으면(옛 계획) 청크 글 그대로
    texts = "\n\n".join(f"[글 {number}]\n{(chunk.get('draft_text') or chunk['content']).strip()}"
                         for number, chunk in enumerate(item["chunks"], 1))
    source = f"문서 제목: {item.get('title') or '-'}\n\n{texts}" if texts else "(글 없음)"
    users = "재학생, 예비 입학생·지원자, 교직원, 외국인, 업체"
    hint_rule = ("'답 근거'에는 질문의 답이 되는 부분을 글에서 그대로 옮긴다."
                 if kind not in ("refuse_guide", "refuse_offtopic") else "'답 근거'는 빈 글로 둔다.")
    if kind == "partial":
        hint_rule = "'답 근거'에는 두 가지 중 글에 답이 있는 쪽의 답이 되는 부분을 글에서 그대로 옮긴다."
    return f"""너는 대학 안내 챗봇의 학습 데이터를 만든다. 아래 학교 문서 글을 읽고, 챗봇 사용자가 물을 만한 질문 하나를 만든다.

[만들 질문]
- {KIND_RULES[kind]} 이 종류를 반드시 지킨다.
- 묻는 사람: {item['user']}. 이 사람으로 쓴다. 이 사람이 이 글을 물을 일이 전혀 없을 때만 {users} 중 물을 만한 사람으로 바꾸고 '묻는 사람'에 적는다.
- 말투: {STYLE_RULES[item['style']]}
- 질문만 읽어도 무엇에 대한 질문인지 알 수 있게, 글에 나온 대상(행사·전형·장학금·프로그램·학과 이름 등)을 질문에 넣는다. '이 전형', '이 대회'처럼 가리키는 말만 쓰지 않는다.
- 실제 사람이 챗봇 입력창에 쓰듯 쓴다. '이 글', '위 문서', 문서 제목을 통째로 옮긴 말은 쓰지 않는다.
- {hint_rule}
- 글로 이 종류의 질문을 만들 수 없으면 '가능'을 false로 한다.

[학교 문서 글]
{source}

JSON 하나만 쓴다: {{"질문": "...", "답 근거": "...", "묻는 사람": "...", "가능": true}}"""


SHAPE_RULES = {
    # 가: 결론 → 근거에 있는 다음 할 일 → 쓴 근거 번호(ADR-0039)
    "ga": f"""1. 첫 문장에 질문에 대한 결론을 쓴다.
2. 근거에 그 일의 신청 방법·기한·문의처·사이트가 있으면 이어서 쓴다. 근거에 없는 것은 쓰지 않는다.
3. 마지막 줄에 답에 쓴 근거 번호를 [출처 N] 형식으로 쓴다. 여럿이면 [출처 1][출처 3]처럼 붙여 쓴다.
4. 근거에 답이 없으면 '{REFUSAL}'로 시작한다. 근거에 이 일을 맡은 부서·연락처·사이트가 있을 때만 이어서 알려 주고 그 근거 번호를 쓴다. 없으면 그 문장 하나만 쓴다.
5. 질문의 일부만 근거에 있으면 있는 것을 먼저 답하고, 없는 것은 '(없는 것)은 {REFUSAL}'라고 쓴 뒤 마지막 줄에 근거 번호를 쓴다.""",
    # 나: 근거 줄 인용 → 결론(RAFT 방식, 1회차 비교용)
    "na": f"""1. 첫 줄은 '근거:'로 시작하고, 답에 쓰는 근거 글을 [출처 N] 번호와 함께 큰따옴표 안에 그대로 옮긴다(한두 줄).
2. 다음 줄은 '답:'으로 시작해 결론을 쓰고, 근거에 있는 신청 방법·기한·문의처·사이트를 이어서 쓴 뒤 마지막에 [출처 N]을 쓴다.
3. 근거에 답이 없으면 '근거: 없음' 다음 줄에 '답: {REFUSAL}'를 쓴다. 근거에 부서·연락처가 있을 때만 이어서 알려 주고 번호를 쓴다.
4. 질문의 일부만 근거에 있으면 있는 것만 인용하고 답한 뒤, 없는 것은 '(없는 것)은 {REFUSAL}'라고 쓴다.""",
}


def target_prompt(item: dict, prompt: str, hint: str, shape: str = "ga") -> str:
    """목표 답 초안 지시문. prompt는 학생 모델이 받는 운영 프롬프트 그대로다."""
    hint_part = (f"\n[질문을 만든 글에서 답이 되는 부분]\n{hint.strip()}\n이 부분이 [검색 근거]의 몇 번에 있는지 찾아 그 번호를 쓴다. "
                 "[검색 근거]에 없으면 근거에 없는 것으로 본다.\n" if hint and hint.strip() else "")
    return f"""너는 대학 안내 챗봇이 배울 모범 답을 쓴다. 아래 [챗봇이 받는 입력]은 챗봇이 실제로 받는 글이다.
그 입력의 필수 답변 규칙과 [검색 근거]만 써서 [사용자 질문]에 답한다.

[모범 답 규칙]
{SHAPE_RULES[shape]}
6. 일반 조언, 추측, 근거에 없는 날짜·숫자·연락처를 쓰지 않는다. 표 값은 질문의 행 이름과 열 이름에 맞는 값만 쓴다.
{hint_part}
[챗봇이 받는 입력]
{prompt}

모범 답 글만 쓴다."""
